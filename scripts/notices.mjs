#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md from the production dependencies pnpm installed.
// Run after changing dependencies: node scripts/notices.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ALLOWED =
  /^(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0|MIT OR Apache-2\.0|\(MIT OR Apache-2\.0\)|MIT OR Apache|Apache-2\.0 OR MIT|\(MIT OR CC0-1\.0\)|\(Apache-2\.0 AND BSD-3-Clause\))$/;
const own = /^(@open-meetings\/|open-meetings$)/;

const report = JSON.parse(
  execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { encoding: "utf8" }),
);
const rows = [];
const unexpected = [];
for (const [license, packages] of Object.entries(report)) {
  for (const pkg of packages) {
    if (own.test(pkg.name)) continue;
    rows.push({
      name: pkg.name,
      versions: pkg.versions.join(", "),
      license,
      homepage: pkg.homepage ?? "",
    });
    if (!ALLOWED.test(license)) unexpected.push(`${pkg.name}: ${license}`);
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const body = `# Third-party notices

Open Meetings is licensed under Apache-2.0. It runs with the open source packages below
(production dependencies of the server, the bot and the panel), each under its own license.
Generated by \`node scripts/notices.mjs\`; do not edit by hand.

## Compatible with, not included

These projects are integrated **only through public protocols**. No code from them is copied,
vendored or derived (ADR 0006):

| Project | License | How Open Meetings talks to it |
| --- | --- | --- |
| OpenBot | PolyForm Noncommercial 1.0.0 | ACP (\`om acp\`) and the OpenAI-compatible endpoint |
| OpenDots (CopilotKit) | MIT | AG-UI (\`/agui\`) and MCP (\`/mcp\`) |
| Attendee | Elastic License 2.0 | Not used; only as an optional external API (ADR 0003) |
| tldraw | tldraw license (key or watermark) | Not used; boards export to Excalidraw's open format instead |

## Packages (${rows.length})

| Package | Version | License |
| --- | --- | --- |
${rows.map((row) => `| ${row.homepage ? `[${row.name}](${row.homepage})` : row.name} | ${row.versions} | ${row.license} |`).join("\n")}
`;
writeFileSync("THIRD_PARTY_NOTICES.md", body);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages`);
if (unexpected.length) {
  console.error(`Licenses that need a review before release:\n${unexpected.join("\n")}`);
  process.exitCode = 1;
}
