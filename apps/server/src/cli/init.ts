import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createInterface } from "node:readline/promises";
import { maskEnvRefs, parseConfig } from "@open-meetings/config";
import { CONFIG_FILE_NAME } from "@open-meetings/core";
import { parseDocument } from "yaml";

export const PROFILES = {
  local: "Everything on this machine (Ollama + local Whisper). No API key, needs a GPU for speed.",
  "cloud-cheap": "Meet captions + small hosted models. Under US$ 0.05 per meeting hour.",
  "cloud-best": "Best quality: Claude for notes and commands.",
  hybrid: "Audio and notes stay local; only commands and minutes go to a hosted model.",
} as const;
export type ProfileName = keyof typeof PROFILES;

export type InitAnswers = {
  profile: ProfileName;
  language: string;
  externalGuests: "allow" | "ask" | "leave";
  internalDomains: string[];
};

/** Finds the example profiles next to the bundle (published) or in the repository. */
function examplesDir(): string {
  const candidates = [
    join(import.meta.dirname, "examples"),
    join(import.meta.dirname, "../../../../examples"),
    join(import.meta.dirname, "../../../examples"),
    resolve("examples"),
  ];
  const found = candidates.find((dir) => existsSync(join(dir, "local.yaml")));
  if (!found) throw new Error("example profiles not found");
  return found;
}

/** Builds the config text and the variables it needs. Pure, so it is testable. */
export function buildConfig(answers: InitAnswers, template: string) {
  const doc = parseDocument(template);
  doc.setIn(["agent", "language"], answers.language);
  doc.setIn(["consent", "externalGuests"], answers.externalGuests);
  doc.setIn(["consent", "internalDomains"], answers.internalDomains);
  const text = doc.toString();
  const variables = [
    ...new Set(
      maskEnvRefs(text)
        .refs.filter((ref) => ref.fallback === undefined)
        .map((ref) => ref.name),
    ),
  ];
  return { text, variables };
}

export function buildEnv(variables: string[]): string {
  const token = () => randomBytes(24).toString("hex");
  const lines = [
    "# Generated by `om init`. Keep this file private.",
    "",
    "# Panel and API token (send as Authorization: Bearer ...).",
    `OM_AUTH_TOKEN=${token()}`,
    "# Shared secret between the server and the bot process.",
    `OM_BOT_TOKEN=${token()}`,
  ];
  const keys = variables.filter((name) => !name.startsWith("OM_"));
  if (keys.length)
    lines.push("", "# API keys this profile needs:", ...keys.map((name) => `${name}=`));
  if (variables.includes("OM_WEBHOOK_URL"))
    lines.push("", "# Optional: receives the minutes when a meeting ends.", "OM_WEBHOOK_URL=");
  return `${lines.join("\n")}\n`;
}

async function ask(defaults: InitAnswers): Promise<InitAnswers> {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  try {
    console.log("Profiles:");
    for (const [name, description] of Object.entries(PROFILES))
      console.log(`  ${name.padEnd(12)} ${description}`);
    const pick = async (question: string, options: readonly string[], fallback: string) => {
      for (;;) {
        const answer = (await rl.question(`${question} [${fallback}]: `)).trim() || fallback;
        if (options.includes(answer)) return answer;
        console.log(`  Choose one of: ${options.join(", ")}`);
      }
    };
    const profile = (await pick("Profile", Object.keys(PROFILES), defaults.profile)) as ProfileName;
    const language =
      (await rl.question(`Language of notes and answers [${defaults.language}]: `)).trim() ||
      defaults.language;
    const externalGuests = (await pick(
      "External guests: allow, ask or leave",
      ["allow", "ask", "leave"],
      defaults.externalGuests,
    )) as InitAnswers["externalGuests"];
    const domains = (
      await rl.question("Your organization's email domains, comma separated (empty to skip): ")
    ).trim();
    return {
      profile,
      language,
      externalGuests,
      internalDomains: domains
        ? domains
            .split(",")
            .map((d) => d.trim())
            .filter(Boolean)
        : [],
    };
  } finally {
    rl.close();
  }
}

export async function runInit(options: {
  profile?: string;
  yes?: boolean;
  force?: boolean;
  dir?: string;
}): Promise<number> {
  const dir = resolve(options.dir ?? ".");
  const configPath = join(dir, CONFIG_FILE_NAME);
  const envPath = join(dir, ".env");
  if (existsSync(configPath) && !options.force) {
    console.error(`${configPath} already exists. Use --force to overwrite it.`);
    return 1;
  }
  if (options.profile && !(options.profile in PROFILES)) {
    console.error(
      `Unknown profile ${options.profile}. Choose one of: ${Object.keys(PROFILES).join(", ")}`,
    );
    return 1;
  }
  const defaults: InitAnswers = {
    profile: (options.profile as ProfileName | undefined) ?? "cloud-cheap",
    language: "pt-BR",
    externalGuests: "allow",
    internalDomains: [],
  };
  const answers = options.yes || !process.stdin.isTTY ? defaults : await ask(defaults);

  const template = readFileSync(join(examplesDir(), `${answers.profile}.yaml`), "utf8");
  const { text, variables } = buildConfig(answers, template);
  parseConfig(text, Object.fromEntries(variables.map((name) => [name, "placeholder"]))); // must stay valid
  writeFileSync(configPath, text);
  console.log(`Wrote ${configPath} (profile ${answers.profile}).`);

  if (!existsSync(envPath) || options.force) {
    writeFileSync(envPath, buildEnv(variables), { mode: 0o600 });
    console.log(`Wrote ${envPath} with fresh tokens.`);
  } else {
    console.log(`${envPath} already exists; left as is.`);
  }
  const keys = variables.filter((name) => !name.startsWith("OM_"));
  console.log(
    [
      "",
      "Next:",
      ...(keys.length ? [`  1. Fill in ${keys.join(", ")} in .env`] : []),
      `  ${keys.length ? 2 : 1}. Check everything: om doctor`,
      `  ${keys.length ? 3 : 2}. Start: om serve   (panel at http://localhost:4319)`,
    ].join("\n"),
  );
  return 0;
}
