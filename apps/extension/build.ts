/**
 * Builds the unpacked extension into dist/ (load it from chrome://extensions in developer
 * mode) and, with --zip, the store-ready open-meetings-extension.zip.
 *
 * The Meet content script is generated from the bot's caption observer, so the bot and the
 * extension read the page with the very same code and selectors.
 *
 * --match <pattern> adds a content-script match pattern (tests run it on a local fake Meet).
 */
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { deflateRawSync } from "node:zlib";
import { OBSERVER_SCRIPT } from "../bot/src/meet/page-script";
import { pageSelectors, SELECTORS } from "../bot/src/meet/selectors";
import { zip } from "../server/src/export/zip";

const here = import.meta.dirname;
const src = join(here, "src");
const args = process.argv.slice(2);
const out = args.includes("--out")
  ? (args[args.indexOf("--out") + 1] ?? join(here, "dist"))
  : join(here, "dist");
const extraMatches = args.flatMap((arg, i) =>
  arg === "--match" && args[i + 1] ? [args[i + 1]] : [],
);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

for (const file of readdirSync(src)) {
  if (file !== "manifest.json") copyFileSync(join(src, file), join(out, file));
}

const manifest = JSON.parse(readFileSync(join(src, "manifest.json"), "utf8"));
manifest.content_scripts[0].matches.push(...extraMatches);
writeFileSync(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

// Content script: the bot's observer, reporting through the extension instead of Playwright.
const captions = `// Generated by apps/extension/build.ts from apps/bot/src/meet. Do not edit.
(() => {
  const selectors = ${JSON.stringify(pageSelectors())};
  const turnOn = ${JSON.stringify(SELECTORS.captions.turnOn)};
  const install = ${OBSERVER_SCRIPT};
  let active = false;
  window.__omEmit = (message) => {
    if (!active) return;
    if (message.kind === "caption") {
      chrome.runtime.sendMessage({ target: "background", cmd: "page", message: { type: "caption", key: message.key, speaker: message.speaker, text: message.text } });
    } else if (message.kind === "caption-removed") {
      chrome.runtime.sendMessage({ target: "background", cmd: "page", message: { type: "caption-removed", key: message.key } });
    } else if (message.kind === "chat") {
      chrome.runtime.sendMessage({ target: "background", cmd: "page", message: { type: "chat", id: message.id, sender: message.sender, text: message.text } });
    }
  };
  chrome.runtime.onMessage.addListener((message) => {
    if (message.target !== "page") return;
    if (message.cmd === "observe") {
      active = true;
      // Captions must be on for there to be anything to read.
      for (const selector of turnOn) {
        const button = document.querySelector(selector);
        if (button) { button.click(); break; }
      }
      install(selectors);
      document.documentElement.dataset.omObserver = "1";
    } else if (message.cmd === "unobserve") {
      active = false;
    }
  });
})();
`;
writeFileSync(join(out, "captions.js"), captions);

// A 128 px icon drawn in code, so the repository needs no binary asset.
writeFileSync(join(out, "icon.png"), iconPng(128));

if (args.includes("--zip")) {
  const files = readdirSync(out).map((name) => ({ name, data: readFileSync(join(out, name)) }));
  writeFileSync(join(here, "open-meetings-extension.zip"), zip(files));
  console.log("wrote apps/extension/open-meetings-extension.zip");
}
console.log(`extension built in ${out}`);

/** Teal rounded square with two white "heads" and a bar: the panel's logo, rasterized. */
function iconPng(size: number): Buffer {
  const pixels = Buffer.alloc(size * (size * 4 + 1));
  const scale = size / 32;
  const inRect = (
    x: number,
    y: number,
    rx: number,
    ry: number,
    w: number,
    h: number,
    r: number,
  ) => {
    const cx = Math.min(Math.max(x, rx + r), rx + w - r);
    const cy = Math.min(Math.max(y, ry + r), ry + h - r);
    return (
      (x - cx) ** 2 + (y - cy) ** 2 <= r * r && x >= rx && x <= rx + w && y >= ry && y <= ry + h
    );
  };
  for (let py = 0; py < size; py++) {
    pixels[py * (size * 4 + 1)] = 0; // no filter
    for (let px = 0; px < size; px++) {
      const x = (px + 0.5) / scale;
      const y = (py + 0.5) / scale;
      let rgba = [0, 0, 0, 0];
      if (inRect(x, y, 0, 0, 32, 32, 8)) rgba = [15, 118, 110, 255];
      if ((x - 11) ** 2 + (y - 13) ** 2 <= 16) rgba = [255, 255, 255, 255];
      if ((x - 21) ** 2 + (y - 13) ** 2 <= 16) rgba = [255, 255, 255, 200];
      if (inRect(x, y, 7, 20, 18, 4, 2)) rgba = [255, 255, 255, 255];
      pixels.set(rgba, py * (size * 4 + 1) + 1 + px * 4);
    }
  }
  const chunk = (type: string, data: Buffer) => {
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([length, body, crc]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8; // bit depth
  header[9] = 6; // RGBA
  const zlibData = Buffer.concat([
    Buffer.from([0x78, 0x9c]),
    deflateRawSync(pixels),
    adler32(pixels),
  ]);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("IDAT", zlibData),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

function crc32(data: Buffer): number {
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let k = 0; k < 8; k++) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function adler32(data: Buffer): Buffer {
  let a = 1;
  let b = 0;
  for (const byte of data) {
    a = (a + byte) % 65521;
    b = (b + a) % 65521;
  }
  const out = Buffer.alloc(4);
  out.writeUInt32BE(((b << 16) | a) >>> 0);
  return out;
}
